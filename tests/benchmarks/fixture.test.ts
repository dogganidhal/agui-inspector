test('the run boundaries: eight finish (success, interrupt and cancellation) and two end in RUN_ERROR', () => {
  const terminals = fixture.map((exchange) => event(exchange.frames.at(-1)!));
  assert.equal(terminals.filter((e) => e.type === 'RUN_FINISHED').length, 8);
  assert.equal(terminals.filter((e) => e.type === 'RUN_ERROR').length, 2);
  const outcomes = terminals.filter((e) => e.type === 'RUN_FINISHED').map((e) => e.outcome.type);
  for (const outcome of ['success', 'interrupt', 'cancelled']) assert.ok(outcomes.includes(outcome), `a ${outcome} outcome`);
  for (const [index, exchange] of fixture.entries()) {
    assert.equal(exchange.index, index);
    const first = event(valid(exchange)[0]!);
    assert.equal(first.runId, exchange.runId);
    assert.equal(first.threadId, exchange.threadId);
  }
  assert.equal(new Set(fixture.map((exchange) => exchange.runId)).size, 10);
});

test('the upstream protocol client accepts every exchange with the invalid frames removed', async () => {
  for (const exchange of fixture) {
    const body = valid(exchange)
      .map((frame) => `data: ${JSON.stringify(JSON.parse(frame.data))}\n\n`)
      .join('');
    const agent = new HttpAgent({
      url: 'http://agent.invalid/run',
      threadId: exchange.threadId,
      fetch: async () => new Response(body, { status: 200 }),
    });
    const terminal = event(exchange.frames.at(-1)!);
    const seen: { failed?: Error; error?: string; outcome?: string } = {};
    await agent.runAgent(
      { runId: exchange.runId },
      {
        onRunFailed: ({ error }) => void (seen.failed = error),
        onRunErrorEvent: ({ event: runError }) => void (seen.error = runError.message),
        onRunFinishedEvent: ({ event: finished }) => void (seen.outcome = finished.outcome?.type),
      },
    );
    assert.equal(seen.failed, undefined, `exchange ${exchange.index}: no sequence or schema failure`);
    assert.equal(seen.error, terminal.type === 'RUN_ERROR' ? terminal.message : undefined);
    assert.equal(seen.outcome, terminal.type === 'RUN_FINISHED' ? terminal.outcome.type : undefined);
  }
});

const EOL = { LF: '\n', CRLF: '\r\n', CR: '\r' } as const;

test('SSE framing: 60% LF, 30% CRLF, 10% CR, and every tenth schema-valid frame has two data lines', () => {
  const counts = { LF: 0, CRLF: 0, CR: 0 };
  for (const exchange of fixture) {
    const perExchange = { LF: 0, CRLF: 0, CR: 0 };
    let ordinal = 0;
    for (const frame of exchange.frames) {
      const eol = EOL[frame.lineEnding];
      perExchange[frame.lineEnding]++;
      if (frame.kind === 'valid') ordinal++;
      const multiline = frame.kind === 'valid' && ordinal % 10 === 0;
      assert.equal(frame.dataLines, multiline ? 2 : 1);

      assert.ok(frame.envelope.endsWith(eol + eol), 'blank line ends the event with the same line ending');
      const lines = frame.envelope.slice(0, -2 * eol.length).split(eol);
      assert.equal(lines.length, frame.dataLines);
      for (const line of lines) {
        assert.ok(line.startsWith('data: '));
        assert.doesNotMatch(line, /[\r\n]/, 'no other line break inside the envelope');
      }
      assert.equal(lines.map((line) => line.slice('data: '.length)).join('\n'), frame.data);
      if (multiline) assert.doesNotThrow(() => JSON.parse(frame.data), 'split at JSON whitespace keeps the data valid');
    }
    assert.deepEqual(perExchange, { LF: 300, CRLF: 150, CR: 50 });
    counts.LF += perExchange.LF; counts.CRLF += perExchange.CRLF; counts.CR += perExchange.CR;
  }
  assert.deepEqual(counts, { LF: 3000, CRLF: 1500, CR: 500 });
});

