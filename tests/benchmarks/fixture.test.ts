test('the manifest is committed, frozen and matches the generator, with hashes recomputed here', () => {
  const file = readFileSync(path.join(root, 'tests', 'benchmarks', 'manifest.json'), 'utf8');
  assert.equal(file, serializeManifest(buildManifest(fixture)), 'run `node tests/benchmarks/generate.ts --write` only for an explicitly reviewed profile change');

  const manifest = JSON.parse(file);
  assert.equal(manifest.seed, '001');
  assert.equal(manifest.frameCount, 5000);
  assert.equal(manifest.schemaValidFrames, 4900);
  assert.equal(manifest.invalidFrames, 100);
  assert.deepEqual(manifest.lineEndings, { LF: 3000, CRLF: 1500, CR: 500 });
  assert.equal(manifest.multilineFrames, 490);
  assert.deepEqual(manifest.typeCounts, PLAN);
  assert.equal(manifest.exchanges.length, 10);

  const wireAll = createHash('sha256');
  let wireBytes = 0;
  for (const [index, exchange] of fixture.entries()) {
    const entry = manifest.exchanges[index];
    const wire = exchange.frames.map((frame) => frame.envelope).join('');
    wireAll.update(wire, 'utf8');
    wireBytes += bytes(wire);
    assert.equal(entry.sha256, sha256(wire), `exchange ${index} wire hash`);
    assert.equal(entry.dataSha256, sha256(exchange.frames.map((frame) => `${frame.data}\n`).join('')), `exchange ${index} data hash`);
    assert.equal(entry.wireBytes, bytes(wire));
    assert.equal(entry.frameCount, 500);
    assert.deepEqual(
      entry.frames,
      exchange.frames.map((frame) => `${frame.type} ${bytes(frame.data)} ${bytes(frame.envelope)}`),
      `exchange ${index} ordered type / payload bytes / envelope bytes`,
    );
  }
  assert.equal(manifest.wireBytes, wireBytes);
  assert.equal(manifest.sha256, wireAll.digest('hex'));
  assert.deepEqual(manifest.exchanges.map((entry: any) => entry.terminal), fixture.map((exchange) => exchange.frames.at(-1)!.type));
});

